// Writes .env.local from the running local Supabase stack, keeping any other
// variables already in it (like AI_GATEWAY_API_KEY).
// Usage: npm run env:local (after `npm run db:start`)
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const HEADER = "# Generated by `npm run env:local`";

const output = execFileSync(
  "supabase",
  [
    "status",
    "-o",
    "env",
    "--override-name",
    "api.url=NEXT_PUBLIC_SUPABASE_URL",
    "--override-name",
    "auth.publishable_key=NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY",
  ],
  { encoding: "utf8", stdio: ["ignore", "pipe", "inherit"], shell: process.platform === "win32" },
);

const lines = output.split(/\r?\n/).filter((line) => line.startsWith("NEXT_PUBLIC_SUPABASE_"));

if (lines.length !== 2) {
  console.error(
    "Couldn't read Supabase status. Is the local stack running? Try `npm run db:start`.",
  );
  process.exit(1);
}

const kept = existsSync(".env.local")
  ? readFileSync(".env.local", "utf8")
      .split(/\r?\n/)
      .filter((line) => line && line !== HEADER && !line.startsWith("NEXT_PUBLIC_SUPABASE_"))
  : [];

writeFileSync(".env.local", [HEADER, ...lines, ...kept].join("\n") + "\n");
console.log("Wrote .env.local");
